    await page.goto(base + '/material-editor.html');
    await page.waitForFunction(() => !document.getElementById('saveMaterial').disabled);
    const buffer = await fs.readFile('checks/fabric-no-dpi.png');
    const upload = async (key, name) => {
      await page.locator('#map-' + key).setInputFiles({ name, mimeType: 'image/png', buffer });
      await page.waitForFunction(({ key, name }) => document.getElementById('file-' + key).textContent === name, { key, name });
    };
    await upload('map', '390WBR_Diffuse.jpg');
    assert.equal(await page.locator('#name').inputValue(), '390');
    assert.equal(await page.locator('#fabricColorCode').inputValue(), 'WBR');
    await upload('map', '389WBK.jpg');
    assert.equal(await page.locator('#fabricColorSwatch').getAttribute('data-configured'), 'true');
    assert.equal(await page.locator('#fabricColorSwatch').evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(246, 246, 246)');
    assert.equal(await page.locator('.fabric-color-swatch-lines').evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(8, 8, 8)');
    await page.locator('#fabricColorCode').fill(' wbk ');
    assert.equal(await page.locator('#fabricColorSwatch').getAttribute('data-configured'), 'true');
    await page.locator('#fabricColorCode').fill('OTHER');
    assert.equal(await page.locator('#fabricColorSwatch').getAttribute('data-configured'), 'false');
    await page.locator('#fabricColorCode').fill('');
    assert.equal(await page.locator('.fabric-color-swatch-lines').evaluate(element => getComputedStyle(element).backgroundColor), 'rgba(0, 0, 0, 0)');
    await upload('map', '389DBW.jpg');
    assert.equal(await page.locator('#name').inputValue(), '389');
    assert.equal(await page.locator('#fabricColorCode').inputValue(), 'DBW');
    await upload('normalMap', '888XYZ_Normal.jpg');
    assert.equal(await page.locator('#name').inputValue(), '389');
    assert.equal(await page.locator('#fabricColorCode').inputValue(), 'DBW');
    const positions = await page.evaluate(() => ['#fabricCategoryRow', '#fabricColorCodeRow', '.pbr-heading-row'].map(selector => document.querySelector(selector).getBoundingClientRect().top));
    assert.deepEqual(positions, [...positions].sort((a, b) => a - b));
    await page.locator('[data-material-type=pattern]').click();
    assert.equal(await page.locator('#fabricColorCodeRow').isVisible(), false);
    await upload('map', '777RED.jpg');
    assert.equal(await page.locator('#name').inputValue(), '389');
    await page.locator('[data-material-type=fabric]').click();
    await upload('map', '389DBW.jpg');
    await page.locator('#name').fill('手动面料名称');
    await page.locator('#fabricColorCode').fill('自定义色号');
    await page.locator('#saveMaterial').click();
    await page.locator('#confirmPreviewGeneration').click();
    await page.waitForFunction(() => document.getElementById('status').textContent === '已生成预览图并保存到资产库');
    const id = new URL(page.url()).searchParams.get('asset');
    assert.equal(state.assets.get(id).metadata.fabricColorCode, '自定义色号');
    await page.reload();
    await page.waitForFunction(() => document.getElementById('name').value === '手动面料名称');
    assert.equal(await page.locator('#fabricColorCode').inputValue(), '自定义色号');
